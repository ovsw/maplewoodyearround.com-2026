import { readFile, writeFile } from "node:fs/promises";
import path from "node:path";
import process from "node:process";
import { fileURLToPath, pathToFileURL } from "node:url";
import { createRequire } from "node:module";

const require = createRequire(import.meta.url);
const scriptDirectory = path.dirname(fileURLToPath(import.meta.url));
const inputsDirectory = path.resolve(scriptDirectory, "../schemas/inputs");
const namesOutputPath = path.join(inputsDirectory, "material-icon-names.ts");
const svgsOutputPath = path.join(inputsDirectory, "material-icons.json");

const STYLE_PREFIX = "twotone-";
// The Website renders stored icon markup through a fail-closed allowlist that
// has no <defs> or <use>; icons drawn with them are left out of the picker.
const UNSUPPORTED_MARKUP = /<(defs|use)\b/;

/** The Material Icons two-tone set: picker names mapped to stored SVG markup. */
export async function buildMaterialIconCatalog() {
  const packagePath = require.resolve("@iconify-json/ic/package.json");
  const packageDirectory = path.dirname(packagePath);
  const { version } = JSON.parse(await readFile(packagePath, "utf8"));
  const set = JSON.parse(await readFile(path.join(packageDirectory, "icons.json"), "utf8"));
  const size = { width: set.width ?? 16, height: set.height ?? 16 };

  const svgs = {};
  for (const [key, icon] of Object.entries(set.icons).sort(([a], [b]) => a.localeCompare(b))) {
    if (!key.startsWith(STYLE_PREFIX) || UNSUPPORTED_MARKUP.test(icon.body)) continue;
    const width = icon.width ?? size.width;
    const height = icon.height ?? size.height;
    svgs[key.slice(STYLE_PREFIX.length)] =
      `<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 ${width} ${height}">${icon.body}</svg>`;
  }
  return { version, svgs };
}

async function run() {
  const { version, svgs } = await buildMaterialIconCatalog();
  const names = Object.keys(svgs);
  await writeFile(
    namesOutputPath,
    `// Generated by studio/scripts/generate-material-icon-catalog.mjs.\n// @iconify-json/ic ${version}, two-tone style; do not edit by hand.\n\nexport const materialIconNames = ${JSON.stringify(names, null, 2)} as const;\n`,
  );
  await writeFile(svgsOutputPath, `${JSON.stringify(svgs, null, 1)}\n`);
}

if (import.meta.url === pathToFileURL(process.argv[1] || "").href) {
  run().catch((error) => {
    console.error(error instanceof Error ? error.message : error);
    process.exitCode = 1;
  });
}
